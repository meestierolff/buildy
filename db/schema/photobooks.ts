export const photobookDrafts = pgTable(
  "photobook_drafts",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    projectId: uuid("project_id").notNull(),
    ownerId: uuid("owner_id").notNull(),
    status: photobookDraftStatusEnum("status").default("draft").notNull(),
    schemaVersion: integer("schema_version").default(1).notNull(),
    projectRevision: bigint("project_revision", { mode: "number" }).notNull(),
    document: jsonb("document").$type<PhotobookDocument>().notNull(),
    documentSha256: text("document_sha256"),
    pageCount: integer("page_count"),
    selectedFormat: text("selected_format").default("a4-landscape-hardcover-v1").notNull(),
    version: optimisticVersion(),
    ...timestamps(),
  },
  (table) => [
    foreignKey({
      name: "photobook_drafts_project_owner_fk",
      columns: [table.projectId, table.ownerId],
      foreignColumns: [projects.id, projects.ownerId],
    }).onDelete("cascade"),
    uniqueIndex("photobook_drafts_project_uq").on(table.projectId),
    unique("photobook_drafts_id_project_uq").on(table.id, table.projectId),
    index("photobook_drafts_owner_status_idx").on(table.ownerId, table.status, table.updatedAt),
    check("photobook_drafts_schema_revision_ck", sql`${table.schemaVersion} > 0 AND ${table.projectRevision} > 0 AND ${table.version} > 0`),
    check("photobook_drafts_document_object_ck", sql`jsonb_typeof(${table.document}) = 'object'`),
    check("photobook_drafts_document_sha_ck", sql`${table.documentSha256} IS NULL OR ${table.documentSha256} ~ '^[0-9a-f]{64}$'`),
    check("photobook_drafts_page_count_ck", sql`${table.pageCount} IS NULL OR ${table.pageCount} > 0`),
    check("photobook_drafts_format_ck", sql`char_length(btrim(${table.selectedFormat})) BETWEEN 1 AND 80`),
  ],
);

